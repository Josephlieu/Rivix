// Writes audit-docs/deliverables/task-27-categories-and-templates.sql: the client's 9 categories, the 42 new product types and
// the 20 new templates (version 1), generated from the code (src/lib/garment-types-data.ts, src/lib/templates-added.ts) so the
// database and the code fallback hold the same data.
// Run: node --experimental-strip-types --no-warnings --import ./scripts/e2e/ts-resolve.mjs scripts/generate-task27-seed.mjs
import fs from 'fs';

const D = await import('../src/lib/garment-types-data.ts');
const A = await import('../src/lib/templates-added.ts');
const C = await import('../src/lib/template-catalog.ts');

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const json = (o) => { const s = JSON.stringify(o); if (s.includes('$tpl$')) throw new Error('body contains the quote marker'); return `$tpl$${s}$tpl$::jsonb`; };
const arr = (a) => (a.length ? `array[${a.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);

const added = new Set(D.ADDED_TYPE_KEYS);
const oldTypes = D.DEFAULT_GARMENT_TYPES.filter((t) => !added.has(t.key));
const newTypes = D.DEFAULT_GARMENT_TYPES.filter((t) => added.has(t.key));
const templates = A.ADDED_TEMPLATES;
const count = (kind) => templates.filter((t) => t.kind === kind).length;
const allCount = (kind) => C.BUILT_IN_TEMPLATES.filter((t) => t.kind === kind).length;
if (oldTypes.length !== 41 || newTypes.length !== 42) throw new Error(`expected 41 older and 42 new types, got ${oldTypes.length} and ${newTypes.length}`);
for (const t of newTypes) if (!A.ADDED_TYPE_TEMPLATES[t.key]) throw new Error(`no template for ${t.key}`);

const sql = `-- Task 27: all 9 RIVIX categories and their templates.
-- GENERATED by scripts/generate-task27-seed.mjs from src/lib/garment-types-data.ts and src/lib/templates-added.ts.
-- Do not edit by hand: change the code and generate it again. Run in Supabase (DEV first) AFTER task-26-templates.sql.
-- Safe to run twice: categories are set to the values below, new types and new templates are added only if missing.
--
-- What it does:
-- 1) The client's 9 categories (3 keep their key; 'Outerwear' becomes 'Winter and Outdoor Workwear' and 'Workwear and
--    Uniforms' becomes 'General Workwear', as approved). Gloves, footwear and other PPE use the new 'product-base' template.
-- 2) The 41 existing types move to their new category and sort. Their key, label, active flag, family and add-ons are NOT
--    touched (nothing is switched off or renamed).
-- 3) ${newTypes.length} new types, each with its template family and add-ons.
-- 4) ${templates.length} new templates at version 1 (${count('base')} base, ${count('family')} families, ${count('module')} add-on modules). Existing template versions
--    are not touched (the task 26 trigger refuses any edit anyway).
-- No new table, so no new RLS policy: garment_categories, garment_types, templates and template_versions keep the policies
-- and grants they already have (templates: reps and admins read, writes only through the server). The check queries at the end show them.
-- Standards in the new templates are CANDIDATES marked "to-verify" (see audit-docs/36-standards-to-verify.md); none is claimed.

begin;

-- 0) Stop early if task 26 has not been run.
do $$ begin
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'garment_categories' and column_name = 'base_template')
     or to_regclass('public.template_versions') is null then
    raise exception 'run task-26-templates.sql first';
  end if;
end $$;

-- 1) New templates and their version 1 (before the categories that point at product-base) ------------------------------------
${templates.map((t) => `insert into public.templates (key, kind, label, description, current_version) values (${lit(t.key)}, ${lit(t.kind)}, ${lit(t.label)}, ${lit(t.description)}, 1) on conflict (key) do nothing;
insert into public.template_versions (template_key, version, body, created_by) values (${lit(t.key)}, 1, ${json(t.body)}, 'seed: task 27') on conflict (template_key, version) do nothing;`).join('\n')}

-- 2) The 9 categories ----------------------------------------------------------------------------------------------------------
${D.DEFAULT_GARMENT_CATEGORIES.map((c) => `insert into public.garment_categories (key, label, sort, base_template) values (${lit(c.key)}, ${lit(c.label)}, ${c.sort}, ${lit(A.CATEGORY_BASE[c.key] ?? 'garment-base')})
  on conflict (key) do update set label = excluded.label, sort = excluded.sort, base_template = excluded.base_template;`).join('\n')}

-- 3) The 41 existing types: new category and sort only ---------------------------------------------------------------------------
${oldTypes.map((t) => `update public.garment_types set category = ${lit(t.category)}, sort = ${t.sort}, updated_at = now() where key = ${lit(t.key)};`).join('\n')}

-- 4) The ${newTypes.length} new types --------------------------------------------------------------------------------------------------------
${newTypes.map((t) => { const m = A.ADDED_TYPE_TEMPLATES[t.key]; return `insert into public.garment_types (key, label, category, sort, active, template_family, template_modules) values (${lit(t.key)}, ${lit(t.label)}, ${lit(t.category)}, ${t.sort}, true, ${lit(m.family)}, ${arr(m.modules ?? [])}) on conflict (key) do nothing;`; }).join('\n')}

commit;

-- Read-only checks after running:
-- select key, label, sort, base_template from public.garment_categories order by sort;            -- 9 rows, gloves/footwear/ppe = product-base
-- select category, count(*) from public.garment_types group by category order by category;       -- ${D.DEFAULT_GARMENT_CATEGORIES.map((c) => `${c.key} ${D.DEFAULT_GARMENT_TYPES.filter((t) => t.category === c.key).length}`).join(', ')}
-- select count(*) from public.garment_types;                                                      -- ${D.DEFAULT_GARMENT_TYPES.length} (more if an admin added any)
-- select kind, count(*) from public.templates group by kind;                                      -- base ${allCount('base')}, family ${allCount('family')}, module ${allCount('module')}
-- select count(*) from public.template_versions where version = 1;                                -- ${C.BUILT_IN_TEMPLATES.length}
-- select key from public.garment_types t where not exists (select 1 from public.templates x where x.key = t.template_family and x.kind = 'family');  -- no rows
-- select relname, relrowsecurity from pg_class where relname in ('garment_categories', 'garment_types', 'templates', 'template_versions');  -- all true
-- select table_name, grantee, privilege_type from information_schema.role_table_grants
--   where table_name in ('garment_categories', 'garment_types', 'templates', 'template_versions') and grantee in ('anon', 'authenticated') order by 1, 2, 3;
`;

fs.mkdirSync('audit-docs/deliverables', { recursive: true });
fs.writeFileSync('audit-docs/deliverables/task-27-categories-and-templates.sql', sql);
console.log(`wrote audit-docs/deliverables/task-27-categories-and-templates.sql: ${D.DEFAULT_GARMENT_CATEGORIES.length} categories, ${oldTypes.length} moved types, ${newTypes.length} new types, ${templates.length} templates, ${sql.length} bytes`);
