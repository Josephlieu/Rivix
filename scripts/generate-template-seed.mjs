// Writes audit-docs/deliverables/task-26-templates.sql: the template tables (task 26) and their seed, generated from the
// templates in code (src/lib/garment-templates.ts), so the database starts with exactly what the code has today.
// Run: node --experimental-strip-types --no-warnings --import ./scripts/e2e/ts-resolve.mjs scripts/generate-template-seed.mjs
import fs from 'fs';

const T = await import('../src/lib/garment-templates.ts');

// The templates in the new shape come from the app itself (BUILT_IN_TEMPLATES), so the seed and the code fallback are the same data.
const C = await import('../src/lib/template-catalog.ts');
// Task 26's own 36 templates only (task 27's are in its own SQL file: scripts/generate-task27-seed.mjs).
const A = await import('../src/lib/templates-added.ts');
const added = new Set(A.ADDED_TEMPLATES.map((t) => t.key));
const templates = C.BUILT_IN_TEMPLATES.filter((t) => !added.has(t.key));

// ---- SQL ------------------------------------------------------------------------------------------------------------------
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const json = (o) => { const s = JSON.stringify(o); if (s.includes('$tpl$')) throw new Error('body contains the quote marker'); return `$tpl$${s}$tpl$::jsonb`; };
const arr = (a) => (a.length ? `array[${a.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);

const sql = `-- Task 26: template system v2 (foundation, no visible change).
-- GENERATED by scripts/generate-template-seed.mjs from src/lib/garment-templates.ts (${templates.length} templates: 1 base, ${T.FAMILIES.length} families, ${T.MODULES.length} modules).
-- Do not edit by hand: change the code and generate it again. Run in Supabase (DEV first) BEFORE deploying task 26.
-- Safe to run twice: tables and columns are created only if missing, and the seed skips templates that already exist.
--
-- Rules:
-- - A template version is never edited or deleted once written (a trigger refuses it, even for the server). A change is a
--   NEW version; tech files record the version they were made with, so an old tech file never changes.
-- - Reps and admins may read templates; nobody writes from the browser (admins will write through the server, task 31).
-- - garment_categories and garment_types stay; two columns are added. template_family keeps working as it does today.

begin;

-- 1) Templates and their versions -----------------------------------------------------------------------------------------
create table if not exists public.templates (
  key text primary key,
  kind text not null check (kind in ('base', 'family', 'module')),
  label text not null,
  description text not null default '',
  current_version integer not null default 1,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.template_versions (
  template_key text not null references public.templates(key) on delete restrict,
  version integer not null check (version >= 1),
  body jsonb not null,
  created_at timestamptz not null default now(),
  created_by text,
  primary key (template_key, version)
);

-- current_version must point at a version that exists (checked at the end of the transaction, so a template and its first
-- version can be added together).
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'templates_current_version_fk') then
    alter table public.templates add constraint templates_current_version_fk
      foreign key (key, current_version) references public.template_versions(template_key, version)
      deferrable initially deferred;
  end if;
end $$;

-- A version is never edited or deleted in place.
create or replace function public.template_versions_are_immutable()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'template versions are never edited or deleted: add a new version instead';
end;
$$;
drop trigger if exists template_versions_immutable on public.template_versions;
create trigger template_versions_immutable before update or delete on public.template_versions
  for each row execute function public.template_versions_are_immutable();

-- 2) Two columns on the existing tables --------------------------------------------------------------------------------------
alter table public.garment_types add column if not exists template_modules text[];
alter table public.garment_categories add column if not exists base_template text not null default 'garment-base';

-- 3) Who may read: admins, and reps whose rep card is active. Only auth.uid() and the signed-in user's own role are used.
create or replace function public.is_admin_or_active_rep()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false)
      or exists (select 1 from public.reps r where r.user_id = auth.uid() and r.active);
$$;
revoke all on function public.is_admin_or_active_rep() from public, anon;
grant execute on function public.is_admin_or_active_rep() to authenticated;

alter table public.templates enable row level security;
alter table public.template_versions enable row level security;

drop policy if exists "admins and reps read templates" on public.templates;
create policy "admins and reps read templates" on public.templates for select to authenticated using (public.is_admin_or_active_rep());
drop policy if exists "admins and reps read template versions" on public.template_versions;
create policy "admins and reps read template versions" on public.template_versions for select to authenticated using (public.is_admin_or_active_rep());

revoke all on public.templates from anon;
revoke all on public.template_versions from anon;
revoke insert, update, delete on public.templates from authenticated;
revoke insert, update, delete on public.template_versions from authenticated;
grant select on public.templates to authenticated;
grant select on public.template_versions to authenticated;

-- 4) Seed: version 1 of every template = today's code ---------------------------------------------------------------------
${templates.map((t) => `insert into public.templates (key, kind, label, description, current_version) values (${lit(t.key)}, ${lit(t.kind)}, ${lit(t.label)}, ${lit(t.description)}, 1) on conflict (key) do nothing;
insert into public.template_versions (template_key, version, body, created_by) values (${lit(t.key)}, 1, ${json(t.body)}, 'seed: task 26') on conflict (template_key, version) do nothing;`).join('\n')}

-- 5) Each garment type's add-on modules (and its family where none is saved yet; a family an admin chose is kept) ----------
${Object.entries(T.TYPE_TEMPLATES).map(([k, v]) => `update public.garment_types set template_modules = ${arr(v.modules ?? [])}, template_family = coalesce(template_family, ${lit(v.family)}) where key = ${lit(k)};`).join('\n')}

commit;

-- Read-only checks after running:
-- select kind, count(*) from public.templates group by kind;                       -- base 1, family ${T.FAMILIES.length}, module ${T.MODULES.length}
-- select count(*) from public.template_versions where version = 1;                 -- ${templates.length}
-- select key, template_family, template_modules from public.garment_types order by sort;
-- select relname, relrowsecurity from pg_class where relname in ('templates', 'template_versions');   -- both true
-- select grantee, privilege_type from information_schema.role_table_grants
--   where table_name in ('templates', 'template_versions') and grantee in ('anon', 'authenticated');   -- authenticated SELECT only
`;

fs.mkdirSync('audit-docs/deliverables', { recursive: true });
fs.writeFileSync('audit-docs/deliverables/task-26-templates.sql', sql);
console.log(`wrote audit-docs/deliverables/task-26-templates.sql: ${templates.length} templates, ${Object.keys(T.TYPE_TEMPLATES).length} type mappings, ${sql.length} bytes`);
